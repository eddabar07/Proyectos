# Crear un programa que describa los pasos para obtener el área de un triángulo.

print("================================================")
print("-----------------AREA TRIANGULO-----------------")
print("================================================")

base = float(input("Ingresa el Valor de la Base del Triangulo: "))
altura = float(input("Ingresa el Valor de la Altura del Triangulo: "))

area = (base * altura) / 2

print(f"El Area del Triangulo es de: {area}")